    .data

input_addr:      .word  0x80          
output_addr:     .word  0x84          

    .org 0x88                         

    .text

_start:
    addi     sp, zero, 768            ; задаём стек 

    jal      ra, b2le_main            ; вызов основной процедуры

    halt                              

b2le_main:
    addi     sp, sp, -4               ; выделяем место в стеке
    sw       ra, 0(sp)                ; сохраняем адрес возврата

    lui      t0, %hi(input_addr)      ; загружаем старшую часть адреса input_addr
    addi     t0, t0, %lo(input_addr)  ; добавляем младшую часть адреса
    lw       t0, 0(t0)                ; t0 = 0x80
    lw       a0, 0(t0)                ; a0 = входное число

    jal      ra, b2le_convert32       ; вызываем преобразование endian

    lui      t0, %hi(output_addr)     ; загружаем старшую часть адреса output_addr
    addi     t0, t0, %lo(output_addr) ; добавляем младшую часть адреса
    lw       t0, 0(t0)                ; t0 = 0x84
    sw       a0, 0(t0)                ; записываем результат в вывод

    lw       ra, 0(sp)                ; восстанавливаем адрес возврата
    addi     sp, sp, 4                ; освобождаем место в стеке
    jr       ra                       ; возврат 

b2le_convert32:
    addi     sp, sp, -4               ; выделяем место под ra
    sw       ra, 0(sp)                ; сохраняем адрес возврата

    jal      ra, b2le_byteswap32      ; вложенный вызов процедуры перестановки байтов

    lw       ra, 0(sp)                ; восстанавливаем адрес возврата
    addi     sp, sp, 4                ; очищаем стек
    jr       ra                       ; возврат в b2le_main

b2le_byteswap32:
    slli     t0, a0, 24               ; младший байт переносим в старший
    srli     t1, a0, 24               ; старший байт переносим в младший

    slli     t2, a0, 16               ; сдвигаем байт CC к старшему краю
    srli     t2, t2, 24               ; оставляем только нужный байт
    slli     t2, t2, 16               ; ставим его на позицию второго байта результата

    srli     t3, a0, 16               ; сдвигаем байт BB к младшему краю
    slli     t3, t3, 24               ; очищаем лишние старшие биты
    srli     t3, t3, 16               ; ставим его на позицию третьего байта результата

    or       a0, t0, t1               ; объединяем крайние байты
    or       a0, a0, t2               ; добавляем второй байт
    or       a0, a0, t3               ; добавляем третий байт

    jr       ra                       ; возврат