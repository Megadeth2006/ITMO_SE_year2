-- Database initialization script for Oracle
-- This script will be executed automatically by Hibernate if hibernate.hbm2ddl.auto is set to "update"
-- But you can also run it manually if needed

-- Create users table
CREATE TABLE users (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(50) UNIQUE NOT NULL,
    password_hash VARCHAR2(255) NOT NULL
);

-- Create points table
CREATE TABLE points (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    x NUMBER(30, 10) NOT NULL,
    y NUMBER(30, 10) NOT NULL,
    r NUMBER(30, 10) NOT NULL,
    in_area NUMBER(1) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    user_id NUMBER NOT NULL,
    CONSTRAINT fk_points_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Create indexes for better performance
CREATE INDEX idx_points_user_id ON points(user_id);
CREATE INDEX idx_points_created_at ON points(created_at DESC);

